//! Render the complete target network once. No source/Live network is changed.
use super::configure::{
    ConfigFile, ConfigurationError, ensure_parent, publish_files, read_config,
    replace_managed_block, validate_destination, validate_planned_parent, validate_root,
};
use crate::config::{
    AddressPreference, CongestionControl, DnsMode, Ipv6Policy, NetworkConfig, QueueDiscipline,
};
use crate::deployment::DeploymentManifest;
use crate::model::{InstallPlan, Target};
use crate::worker::live::ValidatedLivePlan;
use std::fs;
use std::path::Path;

const BEGIN: &str = "# BEGIN rustaller target network";
const END: &str = "# END rustaller target network";
const RESOLVED: &str = "/run/systemd/resolve/stub-resolv.conf";
const SYSCTL: &str = "etc/sysctl.d/90-rustaller-network.conf";

#[derive(Debug, Default, Eq, PartialEq)]
pub struct NetworkServices {
    pub openrc_boot: Vec<&'static str>,
}

/// Pure rendering from validated plan and inherited interface facts. Addresses
/// marked DHCP/RA are snapshots, not additional static addresses to pin at boot.
/// Paths are relative; this function neither reads nor writes the filesystem.
pub fn render_network_configuration(
    plan: &InstallPlan,
    manifest: &DeploymentManifest,
) -> Result<Vec<ConfigFile>, ConfigurationError> {
    plan.validate()
        .map_err(|_| ConfigurationError::InvalidNetwork("invalid installation plan"))?;
    validate_network_policy(plan, manifest)?;
    let net = &plan.system.network;
    let dns = &plan.system.dns;
    let ipv6 = net.ipv6 != Ipv6Policy::Disable;
    let mut files = Vec::new();
    let mut add = |name: &str, contents: String| {
        files.push(ConfigFile {
            path: name.into(),
            contents: contents.into_bytes(),
        })
    };
    if plan.target == Target::Alpine {
        let mut interfaces =
            "# Generated by rustaller\nauto lo\niface lo inet loopback\n\n".to_owned();
        for nic in &manifest.network {
            interfaces.push_str(&format!("# mac {}\nauto {}\n", nic.mac, nic.name));
            let mut configured = false;
            for (family, dynamic, addresses, gateway) in [
                ("inet", nic.dhcp4, &nic.ipv4_addresses, &nic.ipv4_gateway),
                (
                    "inet6",
                    nic.dhcp6 || nic.accept_ra,
                    &nic.ipv6_addresses,
                    &nic.ipv6_gateway,
                ),
            ] {
                if family == "inet6" && !ipv6 {
                    continue;
                }
                if !dynamic && addresses.is_empty() {
                    continue;
                }
                let method = if dynamic {
                    if family == "inet6" && !nic.dhcp6 {
                        "auto"
                    } else {
                        "dhcp"
                    }
                } else {
                    "static"
                };
                interfaces.push_str(&format!("iface {} {family} {method}\n", nic.name));
                configured = true;
                if let Some(mtu) = net.mtu {
                    interfaces.push_str(&format!("    mtu {mtu}\n"));
                }
                if !dynamic {
                    for (index, address) in addresses.iter().enumerate() {
                        if index == 0 {
                            interfaces.push_str(&format!("    address {address}\n"));
                        } else {
                            let version = if family == "inet" { 4 } else { 6 };
                            interfaces.push_str(&format!(
                                "    post-up ip -{version} addr replace {address} dev {}\n",
                                nic.name
                            ));
                        }
                    }
                    if let Some(gateway) = gateway {
                        let version = if family == "inet" { 4 } else { 6 };
                        interfaces.push_str(&format!("    post-up ip -{version} route replace default via {gateway} onlink dev {}\n", nic.name));
                    }
                }
            }
            if !configured {
                interfaces.push_str(&format!("iface {} inet manual\n", nic.name));
                if let Some(mtu) = net.mtu {
                    interfaces.push_str(&format!("    mtu {mtu}\n"));
                }
            }
            // ifupdown-ng treats inet/inet6 as compatibility hints and merges
            // stanzas per link. Explicit native options select the protocols;
            // otherwise dhcpcd could acquire an unrequested address family.
            interfaces.push_str(&format!(
                "    use ipv6\n    ipv6-accept-ra {}\n    ipv6-autoconf {}\n",
                u8::from(ipv6 && nic.accept_ra),
                u8::from(ipv6 && nic.accept_ra)
            ));
            if nic.dhcp4 || (ipv6 && (nic.dhcp6 || nic.accept_ra)) {
                if !nic.dhcp4 && !nic.dhcp6 {
                    interfaces.push_str("    use dhcp\n");
                }
                let mut options = Vec::new();
                if !nic.dhcp4 {
                    options.push("-6");
                } else if !ipv6 || (!nic.dhcp6 && !nic.accept_ra) {
                    options.push("-4");
                }
                if ipv6 && nic.dhcp6 && !nic.accept_ra {
                    options.extend(["--noipv6rs", "--ia_na"]);
                }
                if ipv6 && nic.accept_ra && !nic.dhcp6 {
                    options.push("--nodhcp6");
                }
                interfaces.push_str("    dhcp-program dhcpcd\n");
                if !options.is_empty() {
                    interfaces.push_str(&format!("    dhcp-opts {}\n", options.join(" ")));
                }
            }
            interfaces.push('\n');
        }
        add("etc/network/interfaces", interfaces);
        // Global options precede all interface sections. Both Alpine lease
        // clients must leave explicit DNS alone, including renewal and RA DNS.
        let mut dhcpcd = "# Generated by rustaller\nslaac hwaddr\n".to_owned();
        if dns.mode == DnsMode::Static {
            dhcpcd.push_str("nohook resolv.conf\n");
        }
        if !ipv6 {
            dhcpcd.push_str("noipv6\n");
        }
        add("etc/dhcpcd.conf", dhcpcd);
        add(
            "etc/udhcpc/udhcpc.conf",
            format!(
                "# Generated by rustaller\nRESOLV_CONF=\"{}\"\n",
                if dns.mode == DnsMode::Static {
                    "no"
                } else {
                    "/etc/resolv.conf"
                }
            ),
        );
    } else {
        let networkd_dns = dns
            .networkd_settings()
            .map_err(ConfigurationError::SystemConfig)?;
        for (index, nic) in manifest.network.iter().enumerate() {
            let dhcp = match (nic.dhcp4, ipv6 && nic.dhcp6) {
                (true, true) => "yes",
                (true, false) => "ipv4",
                (false, true) => "ipv6",
                (false, false) => "no",
            };
            let mut text = format!(
                "# Generated by rustaller\n[Match]\nMACAddress={}\n",
                nic.mac
            );
            if let Some(mtu) = net.mtu {
                text.push_str(&format!("\n[Link]\nMTUBytes={mtu}\n"));
            }
            text.push_str(&format!(
                "\n[Network]\nDHCP={dhcp}\nIPv6AcceptRA={}\nLinkLocalAddressing={}\n",
                if ipv6 && nic.accept_ra { "yes" } else { "no" },
                if ipv6 { "ipv6" } else { "no" }
            ));
            for (dynamic, addresses) in [
                (nic.dhcp4, &nic.ipv4_addresses),
                (!ipv6 || nic.dhcp6 || nic.accept_ra, &nic.ipv6_addresses),
            ] {
                if !dynamic {
                    for address in addresses {
                        text.push_str(&format!("Address={address}\n"));
                    }
                }
            }
            // Let native clients renew their own default routes. Pin only
            // static gateways, including off-subnet /32 and /128 providers.
            for (dynamic, gateway) in [
                (nic.dhcp4, &nic.ipv4_gateway),
                (!ipv6 || nic.dhcp6 || nic.accept_ra, &nic.ipv6_gateway),
            ] {
                if !dynamic && let Some(gateway) = gateway {
                    text.push_str(&format!(
                        "\n[Route]\nGateway={gateway}\nGatewayOnLink=yes\n"
                    ));
                }
            }
            if ipv6 && nic.dhcp6 && !nic.accept_ra {
                text.push_str("\n[DHCPv6]\nWithoutRA=solicit\n");
            }
            if let Some(settings) = &networkd_dns {
                text.push('\n');
                text.push_str(settings);
            }
            add(
                &format!("etc/systemd/network/{:02}-{}.network", 10 + index, nic.name),
                text,
            );
        }
    }
    if let Some(resolver) = dns
        .resolv_conf()
        .map_err(ConfigurationError::SystemConfig)?
    {
        add("etc/resolv.conf", resolver);
    }
    let sysctl = net.sysctl();
    if !sysctl.is_empty() {
        add(
            SYSCTL,
            format!("# rustaller target-only network policy\n{sysctl}"),
        );
    }
    Ok(files)
}

/// Also called before destructive installation actions, not just at publication.
pub fn validate_network_policy(
    plan: &InstallPlan,
    manifest: &DeploymentManifest,
) -> Result<(), ConfigurationError> {
    if plan.hold == Some(1) {
        return Err(ConfigurationError::RescuePlan);
    }
    if !plan.target.is_automatic() {
        return Err(ConfigurationError::InvalidNetwork(
            "automatic target required",
        ));
    }
    manifest
        .validate()
        .map_err(|_| ConfigurationError::InvalidNetwork("invalid inherited interface facts"))?;
    plan.system
        .validate(plan.target, plan.hold)
        .map_err(ConfigurationError::SystemConfig)?;
    if plan.system.network.ipv6 == Ipv6Policy::Disable
        && !manifest
            .network
            .iter()
            .any(|nic| nic.dhcp4 || (!nic.ipv4_addresses.is_empty() && nic.ipv4_gateway.is_some()))
    {
        return Err(ConfigurationError::InvalidNetwork(
            "disabling IPv6 would leave no IPv4 default route",
        ));
    }
    Ok(())
}

/// Call only after native package operations have finished using bootstrap DNS.
/// Check every output and service before publishing. Replacements are atomic
/// per file, not a transaction; an I/O failure retains Live for rescue.
pub fn apply_network_configuration(
    root: &Path,
    plan: &ValidatedLivePlan,
    manifest: &DeploymentManifest,
    installed_kernel_config: &str,
) -> Result<NetworkServices, ConfigurationError> {
    validate_root(root)?;
    let plan = plan.plan();
    let net = &plan.system.network;
    let mut files = render_network_configuration(plan, manifest)?;
    let has_sysctl = files.iter().any(|file| file.path == Path::new(SYSCTL));
    let modules = required_modules(net, installed_kernel_config)?;
    if !modules.is_empty() {
        let name = if plan.target == Target::Alpine {
            "etc/modules"
        } else {
            "etc/modules-load.d/90-rustaller-network.conf"
        };
        let path = root.join(name);
        let existing = read_config(&path)?;
        files.push(ConfigFile {
            path: name.into(),
            contents: block(&existing, &format!("{}\n", modules.join("\n")))?.into_bytes(),
        });
    }
    if net.address_preference == AddressPreference::Ipv4 {
        let clean = block(&read_config(&root.join("etc/gai.conf"))?, "")?;
        if clean
            .lines()
            .any(|line| line.split_whitespace().next() == Some("precedence"))
        {
            return Err(ConfigurationError::InvalidConfigFile);
        }
        let body = "precedence ::1/128 50\nprecedence ::/0 40\nprecedence 2002::/16 30\nprecedence ::/96 20\nprecedence ::ffff:0:0/96 100\n";
        files.push(ConfigFile {
            path: "etc/gai.conf".into(),
            contents: block(&clean, body)?.into_bytes(),
        });
    }
    let resolver = root.join("etc/resolv.conf");
    validate_resolver(&resolver)?;
    for file in &mut files {
        file.path = root.join(&file.path);
    }
    let services = NetworkServices {
        openrc_boot: if plan.target == Target::Alpine {
            let mut names = Vec::new();
            if has_sysctl {
                names.push("sysctl");
            }
            if !modules.is_empty() {
                names.push("modules");
            }
            names
        } else {
            vec![]
        },
    };
    let links = super::configure::prepare_openrc(root, &services.openrc_boot)?;
    let automatic_resolved = plan.target != Target::Alpine && plan.system.dns.mode == DnsMode::Auto;
    publish_files(files)?;
    if automatic_resolved {
        ensure_parent(&resolver)?;
        crate::fsutil::atomic_symlink(&resolver, Path::new(RESOLVED))?;
        if fs::read_link(&resolver)? != Path::new(RESOLVED) {
            return Err(ConfigurationError::InvalidConfigFile);
        }
    }
    super::configure::publish_openrc(links)?;
    Ok(services)
}

fn validate_resolver(path: &Path) -> Result<(), ConfigurationError> {
    validate_planned_parent(path)?;
    validate_destination(path, true)?;
    if fs::symlink_metadata(path).is_ok_and(|meta| meta.is_symlink())
        && !matches!(
            fs::read_link(path)?.to_str(),
            Some(RESOLVED | "/run/systemd/resolve/resolv.conf")
        )
    {
        return Err(ConfigurationError::InvalidNetwork(
            "unsupported resolver owner/symlink",
        ));
    }
    Ok(())
}

pub fn needs_kernel_config(net: &NetworkConfig) -> bool {
    !kernel_requirements(net).is_empty()
}

/// This checks installed-kernel capability, not activation in the Live kernel.
pub fn required_modules(
    net: &NetworkConfig,
    kernel_config: &str,
) -> Result<Vec<&'static str>, ConfigurationError> {
    let mut modules = Vec::new();
    for (symbol, module) in kernel_requirements(net) {
        let mut states = kernel_config
            .lines()
            .filter_map(|line| line.split_once('='))
            .filter(|(key, _)| *key == symbol)
            .map(|(_, value)| value);
        match (states.next(), states.next()) {
            (Some("y"), None) => {}
            (Some("m"), None) if !module.is_empty() => {
                modules.push(module);
            }
            _ => return Err(ConfigurationError::UnsupportedNetworkKernel),
        }
    }
    Ok(modules)
}

pub(crate) fn kernel_requirements(net: &NetworkConfig) -> Vec<(&'static str, &'static str)> {
    let mut needed = Vec::new();
    match net.congestion {
        CongestionControl::Bbr => needed.push(("CONFIG_TCP_CONG_BBR", "tcp_bbr")),
        CongestionControl::Cubic => needed.push(("CONFIG_TCP_CONG_CUBIC", "tcp_cubic")),
        CongestionControl::Default => {}
    }
    match net.qdisc {
        QueueDiscipline::Fq => needed.push(("CONFIG_NET_SCH_FQ", "sch_fq")),
        QueueDiscipline::FqCodel => needed.push(("CONFIG_NET_SCH_FQ_CODEL", "sch_fq_codel")),
        QueueDiscipline::Default => {}
    }
    if net.ipv6 == Ipv6Policy::Enable {
        needed.push(("CONFIG_IPV6", "ipv6"));
    }
    if net.syncookies.is_some() {
        needed.push(("CONFIG_SYN_COOKIES", ""));
    }
    needed
}

fn block(existing: &str, body: &str) -> Result<String, ConfigurationError> {
    replace_managed_block(existing, body, BEGIN, END, false)
}
